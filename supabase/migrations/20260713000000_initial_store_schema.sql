create table public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  role public.app_role not null default 'customer',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table public.products (
  id bigint generated by default as identity primary key,
  sku text not null unique,
  slug text not null unique,
  name text not null,
  description text not null default '',
  price numeric(12,2) not null check (price >= 0),
  original_price numeric(12,2) check (original_price is null or original_price >= price),
  fabric text not null,
  category text not null,
  sizes text[] not null default '{}',
  colors text[] not null default '{}',
  images text[] not null default '{}',
  badge text,
  in_stock boolean not null default true,
  is_active boolean not null default true,
  inventory_quantity integer check (inventory_quantity is null or inventory_quantity >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create sequence public.order_number_seq start with 1043;
create function public.next_order_number()
returns text
language sql
volatile
set search_path = ''
as $$
  select '#ASF-' || nextval('public.order_number_seq')::text;
$$;
create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique default public.next_order_number(),
  user_id uuid references auth.users(id) on delete set null,
  customer_name text not null,
  customer_email text not null,
  customer_phone text not null,
  shipping_address text not null,
  shipping_city text not null,
  shipping_country text not null default 'Ghana',
  status public.order_status not null default 'pending',
  payment_status public.payment_status not null default 'pending',
  payment_method text not null check (payment_method in ('momo', 'card', 'cash')),
  subtotal numeric(12,2) not null check (subtotal >= 0),
  shipping_fee numeric(12,2) not null default 50 check (shipping_fee >= 0),
  total numeric(12,2) generated always as (subtotal + shipping_fee) stored,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  sku text not null,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity between 1 and 20),
  selected_size text,
  selected_color text,
  created_at timestamptz not null default now()
);
create table public.custom_orders (
  id uuid primary key default gen_random_uuid(),
  reference_number text not null unique default ('#CUSTOM-' || upper(substr(gen_random_uuid()::text, 1, 8))),
  user_id uuid references auth.users(id) on delete set null,
  customer_name text not null,
  email text not null,
  phone text not null,
  style text not null,
  fabric text not null,
  occasion text,
  budget_range text,
  bust_cm numeric(6,2) check (bust_cm is null or bust_cm > 0),
  waist_cm numeric(6,2) check (waist_cm is null or waist_cm > 0),
  hips_cm numeric(6,2) check (hips_cm is null or hips_cm > 0),
  height_cm numeric(6,2) check (height_cm is null or height_cm > 0),
  notes text,
  reference_images text[] not null default '{}',
  status public.custom_order_status not null default 'new',
  quoted_price numeric(12,2) check (quoted_price is null or quoted_price >= 0),
