create function public.submit_custom_order(request jsonb)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  new_reference text;
begin
  if coalesce(request ->> 'name', '') = ''
    or coalesce(request ->> 'email', '') = ''
    or coalesce(request ->> 'phone', '') = ''
    or coalesce(request ->> 'style', '') = ''
    or coalesce(request ->> 'fabric', '') = '' then
    raise exception 'Missing required custom order details';
  end if;

  insert into public.custom_orders (
    user_id, customer_name, email, phone, style, fabric, occasion, budget_range,
    bust_cm, waist_cm, hips_cm, height_cm, notes
  ) values (
    auth.uid(), request ->> 'name', lower(request ->> 'email'), request ->> 'phone',
    request ->> 'style', request ->> 'fabric', nullif(request ->> 'occasion', ''),
    nullif(request ->> 'budget', ''), nullif(request ->> 'bust', '')::numeric,
    nullif(request ->> 'waist', '')::numeric, nullif(request ->> 'hips', '')::numeric,
    nullif(request ->> 'height', '')::numeric, nullif(request ->> 'notes', '')
  ) returning reference_number into new_reference;

  return new_reference;
end;
$$;
create function public.place_store_order(
  customer jsonb,
  items jsonb,
  payment_method_input text
)
returns table (order_id uuid, order_number text, total numeric)
language plpgsql
security definer
set search_path = ''
as $$
declare
  new_order public.orders;
  item jsonb;
  product public.products;
  calculated_subtotal numeric(12,2) := 0;
begin
  if jsonb_typeof(items) <> 'array' or jsonb_array_length(items) = 0 then
    raise exception 'Your cart is empty';
  end if;

  if payment_method_input not in ('momo', 'card', 'cash') then
    raise exception 'Unsupported payment method';
  end if;

  if coalesce(customer ->> 'name', '') = ''
    or coalesce(customer ->> 'email', '') = ''
    or coalesce(customer ->> 'phone', '') = ''
    or coalesce(customer ->> 'address', '') = ''
    or coalesce(customer ->> 'city', '') = '' then
    raise exception 'Missing required customer details';
  end if;

  for item in select value from jsonb_array_elements(items)
  loop
    if coalesce((item ->> 'quantity')::integer, 0) not between 1 and 20 then
      raise exception 'Invalid item quantity';
    end if;

    select * into product
    from public.products p
    where p.id = (item ->> 'product_id')::bigint
      and p.is_active
      and p.in_stock;

    if not found then
      raise exception 'A product is unavailable';
    end if;

    calculated_subtotal := calculated_subtotal + (product.price * (item ->> 'quantity')::integer);
  end loop;

  insert into public.orders (
    user_id, customer_name, customer_email, customer_phone,
    shipping_address, shipping_city, shipping_country,
    payment_method, subtotal, shipping_fee
  ) values (
    auth.uid(), customer ->> 'name', lower(customer ->> 'email'), customer ->> 'phone',
    customer ->> 'address', customer ->> 'city', coalesce(nullif(customer ->> 'country', ''), 'Ghana'),
    payment_method_input, calculated_subtotal, 50
  ) returning * into new_order;

  for item in select value from jsonb_array_elements(items)
  loop
    select * into product from public.products p where p.id = (item ->> 'product_id')::bigint;
    insert into public.order_items (
      order_id, product_id, product_name, sku, unit_price, quantity, selected_size, selected_color
    ) values (
      new_order.id, product.id, product.name, product.sku, product.price,
      (item ->> 'quantity')::integer, item ->> 'size', item ->> 'color'
    );
  end loop;

  return query select new_order.id, new_order.order_number, new_order.total;
end;
$$;
